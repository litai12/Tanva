import assert from 'node:assert/strict';
import { writeFile, unlink } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import { chromium } from 'playwright';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const name = `.shortcuts-smoke-${process.pid}`;
const files = [path.join(root, `${name}.html`), path.join(root, `${name}.tsx`)];
let server, browser;
try {
  await writeFile(files[0], `<div id="root"></div><script type="module" src="/${name}.tsx"></script>`);
  await writeFile(files[1], `
import React from 'react';
import { createRoot } from 'react-dom/client';
import { MemoryRouter } from 'react-router-dom';
import FloatingHeader from './src/components/layout/FloatingHeader';
import KeyboardShortcuts from './src/components/KeyboardShortcuts';
import ZoomIndicator from './src/components/canvas/ZoomIndicator';
import FocusModeButton from './src/components/canvas/FocusModeButton';
import { useShortcutStore } from './src/stores/shortcutStore';
import { useCanvasStore, useUIStore } from './src/stores';
import { useAIChatStore } from './src/stores/aiChatStore';
import { historyService } from './src/services/historyService';
import i18n from './src/i18n';
import './src/index.css';
import './src/styles/chat.css';
window.shortcutSmoke={undo:0,redo:0,store:useShortcutStore,canvas:useCanvasStore,ui:useUIStore,theme:useAIChatStore,i18n};
useUIStore.setState({focusMode:false});
historyService.undo=async()=>{window.shortcutSmoke.undo++};
historyService.redo=async()=>{window.shortcutSmoke.redo++};
historyService.captureInitialIfEmpty=async()=>{};
createRoot(document.getElementById('root')).render(<MemoryRouter><FloatingHeader/><KeyboardShortcuts/><ZoomIndicator/><FocusModeButton/><input id="editing" style={{position:'absolute',top:100,left:20}}/><div id="editable" contentEditable suppressContentEditableWarning style={{position:'absolute',top:125,left:20}}>Editable text</div><div id="surface" tabIndex={-1} style={{position:'absolute',top:150,left:20,width:200,height:200}}>Canvas test surface</div><div id="dialog" role="dialog" aria-modal="true" style={{display:'none',position:'absolute',top:400,left:20}}><button id="dialog-first">First</button><button id="dialog-second">Second</button></div><div id="legacy-dialog" className="fixed inset-0" style={{display:'none'}}><button>Legacy dialog</button></div></MemoryRouter>);
`);
  server = await createServer({ root, server: { host: '127.0.0.1', port: 0 } });
  await server.listen();
  const port = server.httpServer.address().port;
  browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/api/**', route => route.fulfill({ json: {} }));
  const url = `http://127.0.0.1:${port}/${name}.html?lang=zh-CN`;
  await page.goto(url);
  const openSettings = async () => {
    await page.getByTitle('设置', { exact: true }).click();
    await page.locator('.tanva-settings-sidebar').getByRole('button', { name: '快捷键', exact: true }).click();
    await page.locator('[data-shortcut-action="undo"]').waitFor();
  };
  const row = id => page.locator(`[data-shortcut-action="${id}"]`);
  const record = async (id, key) => {
    await row(id).getByRole('button', { name: /编辑|录入|更改|Edit|Record/ }).first().click();
    await page.keyboard.press(key);
  };
  const focusSurface = () => page.locator('#surface').focus();
  const focusMode = () => page.evaluate(() => window.shortcutSmoke.ui.getState().focusMode);
  const eye = page.locator('.tanva-focus-mode-button button');
  await eye.waitFor();
  assert.match(await eye.getAttribute('title'), /Tab/);
  await focusSurface();
  await page.keyboard.down('Tab');
  assert.equal(await focusMode(), true, 'Default Tab enters focus mode');
  await page.waitForFunction(() => document.querySelector('.tanva-header-shell')?.getAttribute('aria-hidden') === 'true');
  assert.equal(await page.evaluate(() => document.activeElement.id), 'surface', 'Handled Tab does not advance focus');
  await page.keyboard.down('Tab');
  assert.equal(await focusMode(), true, 'Holding Tab does not toggle repeatedly');
  await page.keyboard.up('Tab');
  await page.keyboard.press('Tab');
  assert.equal(await focusMode(), false, 'Tab restores the hidden UI');
  await eye.click();
  assert.equal(await focusMode(), true, 'Eye click uses the same state');
  await eye.click();
  assert.equal(await focusMode(), false);
  await focusSurface();
  await page.keyboard.press('Shift+Tab');
  assert.equal(await focusMode(), false, 'Shift+Tab remains normal focus navigation');
  for (const selector of ['#editing', '#editable']) {
    await page.locator(selector).focus();
    await page.keyboard.press('Tab');
    assert.equal(await focusMode(), false, 'Editable fields retain Tab navigation');
  }
  await focusSurface();
  await page.evaluate(() => document.querySelector('#surface').dispatchEvent(new KeyboardEvent('keydown', {key:'Tab',code:'Tab',bubbles:true,isComposing:true,cancelable:true})));
  assert.equal(await focusMode(), false, 'IME does not toggle UI');
  await page.evaluate(() => { document.querySelector('#dialog').style.display = 'block'; });
  await page.locator('#dialog-first').focus();
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(() => document.activeElement.id), 'dialog-second', 'Modal Tab navigation remains intact');
  assert.equal(await focusMode(), false);
  await focusSurface();
  await page.keyboard.press('Tab');
  assert.equal(await focusMode(), false, 'Visible dialog blocks toggling even with focus on canvas');
  await page.evaluate(() => { document.querySelector('#dialog').style.display = 'none'; document.querySelector('#legacy-dialog').style.display = 'block'; });
  await focusSurface();
  await page.keyboard.press('Tab');
  assert.equal(await focusMode(), false, 'Legacy modal backdrops also block toggling');
  await page.evaluate(() => { document.querySelector('#legacy-dialog').style.display = 'none'; window.shortcutSmoke.theme.setState({isMaximized:true}); });
  await focusSurface();
  await page.keyboard.press('Tab');
  assert.equal(await focusMode(), false, 'Maximized chat retains Tab navigation');
  await page.evaluate(() => window.shortcutSmoke.theme.setState({isMaximized:false}));
  await openSettings();
  assert.match(await row('focusMode').innerText(), /Tab/);
  await record('focusMode', 'Tab');
  assert.equal(await focusMode(), false, 'Recording Tab cannot execute focus mode');
  await record('focusMode', 'Alt+f');
  await row('focusMode').getByRole('button', { name: /编辑|录入|更改|Edit|Record/ }).first().focus();
  await page.keyboard.press('Alt+f');
  assert.equal(await focusMode(), false, 'Settings suppress the custom UI binding');
  await record('undo', 'Control+Alt+U');
  await page.waitForFunction(() => window.shortcutSmoke.store.getState().overrides.undo?.[0] === 'Mod+Alt+U');
  assert.equal(await page.evaluate(() => window.shortcutSmoke.undo), 0, 'Recording must not invoke undo');
  await record('redo', 'Control+Alt+U');
  await page.getByRole('alert').waitFor();
  assert.equal(await page.evaluate(() => window.shortcutSmoke.store.getState().overrides.redo), undefined);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.tanva-settings-modal').count(), 1, 'Escape cancels recording first');
  await page.screenshot({ path: '/tmp/tanva-custom-shortcuts-light.png' });
  await page.keyboard.press('Escape');
  await focusSurface();
  assert.match(await eye.getAttribute('title'), /(?:Alt|⌥).*F/);
  await page.keyboard.press('Tab');
  assert.equal(await focusMode(), false, 'Old focus binding stops working after rebinding');
  await focusSurface();
  await page.keyboard.press('Alt+f');
  assert.equal(await focusMode(), true, 'Custom binding enters focus mode');
  await page.keyboard.press('Alt+f');
  assert.equal(await focusMode(), false, 'Custom binding restores hidden UI');
  await page.locator('#editing').focus();
  await page.keyboard.press('Alt+f');
  assert.equal(await focusMode(), false, 'Custom binding is also suppressed in text inputs');
  await focusSurface();
  await page.keyboard.press('Control+z');
  assert.equal(await page.evaluate(() => window.shortcutSmoke.undo), 0, 'Old binding is inactive');
  await page.keyboard.press('Control+Alt+u');
  assert.equal(await page.evaluate(() => window.shortcutSmoke.undo), 1, 'Custom binding invokes actual handler');
  await page.keyboard.press('Meta+Alt+u');
  assert.equal(await page.evaluate(() => window.shortcutSmoke.undo), 2, 'Cmd works with the same binding');
  await page.locator('#editing').focus();
  await page.keyboard.press('Control+Alt+u');
  assert.equal(await page.evaluate(() => window.shortcutSmoke.undo), 2, 'Text input keeps native behavior');
  await page.reload();
  await page.waitForFunction(() => Boolean(window.shortcutSmoke));
  await focusSurface();
  await page.keyboard.press('Alt+f');
  assert.equal(await focusMode(), true, 'Focus mode binding survives refresh');
  await page.keyboard.press('Alt+f');
  assert.equal(await focusMode(), false);
  await page.keyboard.press('Control+Alt+u');
  assert.equal(await page.evaluate(() => window.shortcutSmoke.undo), 1, 'Binding persists after reload');
  await openSettings();
  await row('focusMode').getByRole('button', { name: /清除|Clear/ }).click();
  await row('redo').getByRole('button', { name: /清除|Clear/ }).click();
  await page.keyboard.press('Escape');
  await focusSurface();
  assert.doesNotMatch(await eye.getAttribute('title'), /Tab|Alt|⌥/);
  await page.keyboard.press('Alt+f');
  await page.keyboard.press('Tab');
  assert.equal(await focusMode(), false, 'Clear disables both default and custom UI bindings');
  await focusSurface();
  await page.keyboard.press('Control+Shift+z');
  await page.keyboard.press('Control+y');
  assert.equal(await page.evaluate(() => window.shortcutSmoke.redo), 0, 'Clear disables all default aliases');
  await openSettings();
  await row('undo').getByRole('button', { name: /恢复|Restore/ }).click();
  await page.getByRole('button', { name: /全部恢复默认|恢复全部默认|Reset all/ }).click();
  await page.waitForFunction(() => Object.keys(window.shortcutSmoke.store.getState().overrides).length === 0);
  await page.evaluate(() => { window.shortcutSmoke.theme.setState({ chatTheme: 'black' }); document.documentElement.classList.add('dark'); document.body.classList.add('tanva-premium-black-theme'); });
  assert.equal(await page.locator('.tanva-settings-modal').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(22, 22, 22)');
  await page.screenshot({ path: '/tmp/tanva-custom-shortcuts-dark.png' });
  await page.evaluate(() => window.shortcutSmoke.i18n.changeLanguage('en-US'));
  await page.locator('.tanva-settings-sidebar').getByRole('button', { name: /Keyboard shortcuts/i }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await row('undo').isVisible(), true);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'Mobile has no horizontal page overflow');
  await page.keyboard.press('Escape');
  await focusSurface();
  await page.keyboard.press('Tab');
  assert.equal(await focusMode(), true, 'Reset restores default Tab');
  await page.keyboard.press('Tab');
  assert.equal(await focusMode(), false);
  await page.keyboard.press('Control+z');
  assert.equal(await page.evaluate(() => window.shortcutSmoke.undo), 2, 'Reset restores the original handler');
  assert.deepEqual(errors, []);
  console.log('Custom shortcuts browser checks passed: settings entry, recording, conflict, Escape, runtime rebinding, Ctrl/Cmd, editable protection, persistence, clearing aliases, reset, themes, English and mobile; eye-button default/custom/clear/reset/refresh, UI restoration, modal navigation, IME and held-key protection.');
} finally {
  await browser?.close();
  await server?.close();
  await Promise.all(files.map(file => unlink(file).catch(() => {})));
}
